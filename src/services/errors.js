'use strict';

/** Erro de domínio: a mensagem é segura para mostrar ao usuário. */
class AppError extends Error {
  constructor(code, userMessage, meta = {}) {
    super(userMessage);
    this.name = 'AppError';
    this.code = code;
    this.userMessage = userMessage;
    this.meta = meta;
  }
}

